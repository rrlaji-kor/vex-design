"""Firebase 없이 기기마다 저장 · Claude 앱 내용 가져오기 · 구상안 보내기/받기 테스트"""
import asyncio, json, os, re
from playwright.async_api import async_playwright
BASE = 'http://127.0.0.1:8766/'
OUT = 'shots_local'; os.makedirs(OUT, exist_ok=True)
errors, fails = [], []
def check(c, m):
    print(('  ok   ' if c else '  FAIL ') + m)
    if not c: fails.append(m)
async def setup(ctx):
    async def route(r):
        if 'fonts.g' in r.request.url: await r.fulfill(status=200, content_type='text/css', body='')
        else: await r.continue_()
    await ctx.route('**/*', route)
def watch(page, tag):
    page.on('console', lambda m: errors.append(f'[{tag}] {m.type}: {m.text}') if m.type in ('error', 'warning') and 'Service Worker registration blocked' not in m.text else None)
    page.on('pageerror', lambda e: errors.append(f'[{tag}] PAGEERROR: {e}'))
LAUNCH = ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader']

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=LAUNCH)
        # ---------- 보호자 폰 ----------
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True, service_workers='block')
        await ctx.grant_permissions(['clipboard-read', 'clipboard-write'], origin=BASE.rstrip('/'))
        await setup(ctx)
        me = await ctx.new_page(); watch(me, 'me')
        await me.goto(BASE); await me.wait_for_timeout(900)
        print('— 처음 열기')
        check(await me.evaluate('S.mode') == 'local', '기기 저장 모드')
        check(await me.evaluate('els.banner.hidden'), '경고 띠 없음')
        check((await me.inner_text('#sync')).strip() in ('이 기기에 저장됨', ''), f'저장 표시: {await me.evaluate("els.sync.textContent")!r}')
        check(await me.evaluate('S.curId') == 'd1' and await me.evaluate('S.history.length') == 21, 'Claude 앱 구상안 1개·기록 21개 가져옴')
        mb = await me.evaluate("curDesign().mods.brain"); check(mb.get('dy') == 7 and mb.get('dz') == 2, f'Claude 앱에서 옮긴 자리 그대로: {mb}')
        check(await me.evaluate("!!localStorage.getItem('vexiq-design-seeded-v1')"), '가져오기 표시 남김')
        await me.click('.ptab[data-tab=hist]'); await me.wait_for_timeout(200)
        row = (await me.locator('.hrow').first.inner_text()).replace('\n', ' ')
        check('Claude 앱' in row, f'옛 기록에 이름: {row[:60]}')
        hint = await me.inner_text('#pbody')
        check('이 기기에서 바꾼 것만' in hint, '기록 설명이 기기 저장에 맞게')
        print('— 고치고 다시 열기')
        await me.click('.ptab[data-tab=combo]'); await me.wait_for_timeout(150)
        await me.click('.card[data-k=launch][data-v=catapult]'); await me.wait_for_timeout(200)
        await me.click('.card[data-k=intake][data-v=roller]'); await me.wait_for_timeout(200)
        await me.reload(); await me.wait_for_timeout(900)
        check(await me.evaluate('curDesign().opts.launch') == 'catapult' and await me.evaluate('curDesign().opts.intake') == 'roller', '다시 열어도 남음')
        check(await me.evaluate('S.history.length') == 23 and await me.evaluate("Object.values(S.designs).length") == 1, '가져오기를 또 하지 않음 (기록 23, 구상안 1)')
        print('— 보내기')
        await me.click('.ptab[data-tab=designs]'); await me.wait_for_timeout(200)
        await me.evaluate('window.scrollTo(0, 0)')
        await me.click('[data-act=shareDesign][data-id=d1]'); await me.wait_for_timeout(600)
        url = await me.evaluate('navigator.clipboard.readText()')
        check(url.startswith(BASE + '?d=z'), f'링크 복사됨 ({len(url)}자): {url[:60]}…')
        check('복사했어요' in await me.inner_text('#toasts'), '복사 알림')
        await me.screenshot(path=f'{OUT}/l01_designs_phone.png', full_page=True)
        print('— 지안이가 링크로 받기 (다른 기기)')
        ctx2 = await b.new_context(viewport={'width': 1440, 'height': 900}, service_workers='block')
        await setup(ctx2)
        jn = await ctx2.new_page(); watch(jn, 'jian')
        await jn.goto(url); await jn.wait_for_timeout(1000)
        bn = await jn.inner_text('#banner')
        check(not await jn.evaluate('els.banner.hidden') and '추가할까요' in bn, f'받은 구상안 띠: {bn!r}')
        check('?d=' not in jn.url, f'주소에서 링크 내용 지움: {jn.url}')
        await jn.screenshot(path=f'{OUT}/l02_mac_incoming.png')
        await jn.click('#banner [data-act=acceptIncoming]'); await jn.wait_for_timeout(600)
        d = await jn.evaluate('curDesign()')
        check(d['name'] == '구상안 1 (2)' and d['opts']['launch'] == 'catapult' and d['opts']['intake'] == 'roller', f'받은 구상안 추가: {d["name"]} · {d["opts"]["launch"]} · {d["opts"]["intake"]}')
        check(d['mods'].get('brain') == {'dx': 0, 'dy': 7, 'dz': 2}, '부품 자리도 같이 옴')
        check(await jn.evaluate('els.banner.hidden'), '추가하면 띠 사라짐')
        await jn.click('.ptab[data-tab=hist]'); await jn.wait_for_timeout(200)
        row = (await jn.locator('.hrow').first.inner_text()).replace('\n', ' ')
        check('받은 구상안 추가' in row, f'기록: {row[:50]}')
        await jn.screenshot(path=f'{OUT}/l03_mac_after_accept.png')
        print('— 붙여 넣어 받기')
        await jn.click('.ptab[data-tab=designs]'); await jn.wait_for_timeout(200)
        await jn.fill('#pasteIn', '이거 받아 ' + url + ' ')
        await jn.click('[data-act=pasteImport]'); await jn.wait_for_timeout(600)
        check(await jn.evaluate('curDesign().name') == '구상안 1 (3)' or await jn.evaluate("liveDesigns().length") == 3, f'붙여 넣기로 추가: {await jn.evaluate("liveDesigns().map(x=>x.name)")}')
        await jn.fill('#pasteIn', 'https://example.com/abc'); await jn.click('[data-act=pasteImport]'); await jn.wait_for_timeout(300)
        check('링크가 아니에요' in await jn.inner_text('#toasts'), '엉뚱한 링크는 거절')
        print('— 망가진 링크 · 이상한 내용')
        await jn.goto(BASE + '?d=zAAAAAAAAAAAAAAAA'); await jn.wait_for_timeout(900)
        check('망가졌어요' in await jn.inner_text('#toasts') and await jn.evaluate('els.banner.hidden'), '망가진 링크 알림')
        evil = await jn.evaluate("""async () => {
          const raw = new TextEncoder().encode(JSON.stringify({v:1, d:{name:'<img src=x onerror=alert(1)>해킹', frame:{w:999,l:-5}, opts:{launch:'rocket', bands:'99', rail:40, pull:'winch'},
            mods:{launcher:{dx:1e9,dy:'2',dz:0}, evil:{dx:1}}, edits:{'a b':{dx:1}, motor_1L:{dx:2, hidden:1, zz:5}}, added:{p1:{kind:'cBeam', name:'<b>x</b>', c:[1,2,3], s:[1,10,0.5]}, p2:{kind:'nuke', c:[0,0,0], s:[1,1,1]}}, __proto__x:1, extra:{a:1}}}));
          return 'z' + b64u.enc(await zipBytes(raw, true)); }""")
        await jn.goto(BASE + '?d=' + evil); await jn.wait_for_timeout(900)
        inc = await jn.evaluate('S.incoming')
        check('<' not in inc['name'] and inc['frame'] == {'w': 24, 'l': 19} and inc['opts']['launch'] is None and inc['opts']['bands'] == 8, f'이상한 값 걸러냄: {inc["name"]} {inc["frame"]} {inc["opts"]["launch"]} {inc["opts"]["bands"]}')
        check(list(inc['mods']) == ['launcher'] and inc['mods']['launcher']['dx'] == 60 and list(inc['edits']) == ['motor_1L'] and list(inc['added']) == ['p1'] and 'extra' not in inc, '모르는 칸은 버림')
        check(await jn.evaluate("document.querySelectorAll('#banner img').length") == 0, '이름 속 태그가 화면에 안 들어감')
        await jn.click('#banner [data-act=dismissIncoming]'); await jn.wait_for_timeout(200)
        check(await jn.evaluate("liveDesigns().length") == 3, '닫으면 추가 안 함')
        print('— 카톡 안 브라우저에서 열기')
        ctx3 = await b.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True, service_workers='block',
                                   user_agent='Mozilla/5.0 (Linux; Android 14; SM-S921N) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Mobile Safari/537.36;KAKAOTALK 2410090')
        await setup(ctx3)
        kk = await ctx3.new_page(); watch(kk, 'kakao')
        tried = []
        kk.on('request', lambda r: tried.append(r.url) if r.url.startswith('kakaotalk:') else None)
        kk.on('framenavigated', lambda f: None)
        await kk.goto(url, wait_until='domcontentloaded'); await kk.wait_for_timeout(1500)
        bn = await kk.inner_text('#banner')
        check('카톡 안에서는' in bn and await kk.locator('#banner [data-act=openExternal]').count() == 1, f'카톡 안내: {bn!r}')
        check(await kk.evaluate('S.incomingUrl') == url, '바깥 브라우저로 넘길 주소 기억')
        await kk.evaluate('window.scrollTo(0,0)')
        await kk.screenshot(path=f'{OUT}/l04_kakao.png')
        for pg, nm in [(me, 'phone'), (jn, 'mac'), (kk, 'kakao')]:
            ov = await pg.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')
            check(ov == 0, f'가로 넘침 없음 ({nm}: {ov})')
        await b.close()
    errs = [e for e in errors if 'kakaotalk' not in e.lower()]
    print('\n'.join(errs) if errs else 'NO CONSOLE ERRORS')
    print(f'\n{len(fails)} FAIL' if fails else '\nALL PASS')
asyncio.run(main())
