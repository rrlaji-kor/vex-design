import asyncio, json, os, re, shutil, sys
from playwright.async_api import async_playwright
BASE = 'http://127.0.0.1:8766/'
FAKE = open('fakefirebase.js').read()
CFG = "window.FIREBASE_CONFIG = {apiKey:'test-key', authDomain:'test.firebaseapp.com', projectId:'test', appId:'1:1:web:1'};"
OUT = 'shots_pwa'; os.makedirs(OUT, exist_ok=True)
errors, fails = [], []
def check(cond, msg):
    print(('  ok   ' if cond else '  FAIL ') + msg)
    if not cond: fails.append(msg)

async def setup(ctx):
    async def route(r):
        u = r.request.url.split('?')[0]
        if u.endswith('/vendor/firebase-app-compat.js'): await r.fulfill(status=200, content_type='application/javascript', body=FAKE)
        elif '/vendor/firebase-' in u: await r.fulfill(status=200, content_type='application/javascript', body='/* stub */')
        elif u.endswith('/config.js'): await r.fulfill(status=200, content_type='application/javascript', body=CFG)
        elif 'fonts.g' in u: await r.fulfill(status=200, content_type='text/css', body='')
        else: await r.continue_()
    await ctx.route('**/*', route)

def watch(page, tag):
    page.on('console', lambda m: errors.append(f'[{tag}] {m.type}: {m.text}') if m.type in ('error', 'warning') else None)
    page.on('pageerror', lambda e: errors.append(f'[{tag}] PAGEERROR: {e}'))

async def st(page): return await page.evaluate('window.__fs()')
async def gate(page): return await page.evaluate("({hidden: document.getElementById('gate').hidden, msg: document.getElementById('gateMsg').textContent, login: !document.getElementById('gateLogin').hidden, other: !document.getElementById('gateOut').hidden})")
async def toasts(page): return await page.inner_text('#toasts')

