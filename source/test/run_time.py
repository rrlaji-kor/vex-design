"""만들기 탭 예상 시간 테스트: 단계·묶음·남은 시간 · 우리 팀 속도 · 실제 시간 기록"""
import asyncio, os
from playwright.async_api import async_playwright
BASE = 'http://127.0.0.1:8766/'
OUT = 'shots_build'; os.makedirs(OUT, exist_ok=True)
errors, fails = [], []
def check(c, m):
    print(('  ok   ' if c else '  FAIL ') + m)
    if not c: fails.append(m)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True, service_workers='block')
        async def route(r):
            if 'fonts.g' in r.request.url: await r.fulfill(status=200, content_type='text/css', body='')
            else: await r.continue_()
        await ctx.route('**/*', route)
        me = await ctx.new_page()
        me.on('console', lambda m: errors.append(f'{m.type}: {m.text}') if m.type in ('error', 'warning') and 'Service Worker' not in m.text else None)
        me.on('pageerror', lambda e: errors.append(f'PAGEERROR: {e}'))
        await me.goto(BASE); await me.wait_for_timeout(900)
        for k, v in [('launch', 'sling_back'), ('intake', 'roller'), ('brain', 'back')]:
            await me.click(f'.card[data-k={k}][data-v={v}]'); await me.wait_for_timeout(150)
        await me.click('.ptab[data-tab=build]'); await me.wait_for_timeout(300)
        t = await me.inner_text('.tline')
        check('6~9.5시간' in t and '3~5번' in t, f'남은 시간 (보통): {t!r}')
        asides = await me.eval_on_selector_all('#pbody .sec-h .aside', 'a => a.map(x => x.textContent)')
        check('약 30~45분' in asides and '약 1~1.5시간' in asides and '약 4~6시간' in asides, f'묶음 합계: {asides}')
        tm = await me.inner_text('.bstep[data-id=sl-rail] .tm')
        check(tm == '약 30~45분', f'단계 시간: {tm!r}')
        await me.click('.speed [data-v=skilled]'); await me.wait_for_timeout(250)
        t = await me.inner_text('.tline')
        check('3.5~5.5시간' in t, f'익숙함 속도: {t!r}')
        await me.click('.speed [data-v=mine]', force=True); await me.wait_for_timeout(250)
        check(await me.evaluate("S.prefs.buildSpeed") == 'skilled' and '하나 이상' in await me.inner_text('#toasts'), '기록 없으면 "우리 기록" 안 켜짐')
        await me.click('.speed [data-v=normal]'); await me.wait_for_timeout(200)
        await me.click('.bstep[data-id=prep] .bs-h'); await me.wait_for_timeout(400)
        await me.fill('#bt-prep', '40'); await me.press('#bt-prep', 'Enter'); await me.wait_for_timeout(400)
        rec = await me.evaluate("S.prefs.buildTime[S.curId].prep")
        check(rec['m'] == 40 and rec['e'] == 25, f'걸린 시간 저장: {rec}')
        check('실제 40분' in await me.inner_text('.bstep[data-id=prep] .tm'), '단계에 실제 시간 표시')
        await me.click('.speed [data-v=mine]'); await me.wait_for_timeout(250)
        sp = await me.inner_text('.speed')
        check(await me.evaluate("S.prefs.buildSpeed") == 'mine' and '160%' in sp, f'우리 기록 속도: {sp!r}')
        await me.click('.bstep.open .donebox'); await me.wait_for_timeout(300)
        t = await me.inner_text('.tline')
        check('전체 약' in t, f'다 한 단계는 남은 시간에서 빠짐: {t!r}')
        await me.reload(); await me.wait_for_timeout(900)
        await me.click('.ptab[data-tab=build]'); await me.wait_for_timeout(300)
        check(await me.evaluate("S.prefs.buildSpeed") == 'mine' and 'prep' in await me.evaluate("Object.keys(S.prefs.buildTime[S.curId])"), '다시 열어도 속도·기록 남음')
        await me.click('.bstep[data-id=prep] .bs-h'); await me.wait_for_timeout(300)
        await me.fill('#bt-prep', ''); await me.press('#bt-prep', 'Enter'); await me.wait_for_timeout(300)
        check('prep' not in await me.evaluate("Object.keys(S.prefs.buildTime[S.curId] || {})"), '칸을 비우면 기록 지움')
        await me.click('.bstep[data-id=sl-winch] .bs-h'); await me.wait_for_timeout(400)
        check('걸쇠를 풀 장치' in await me.inner_text('.bstep.open .trec'), '윈치 시간 설명')
        await me.evaluate('window.scrollTo(0,0)')
        await me.screenshot(path=f'{OUT}/t01_time_phone.png', full_page=True)
        # 포맷 함수
        fm = await me.evaluate("[fmtDur(10,15), fmtDur(45,70), fmtDur(65,100), fmtDur(285,450), fmtDur(100,160), fmtDur(60,60), fmtDur(3,4)]")
        check(fm == ['10~15분', '45분~1시간', '1~1.5시간', '5~7.5시간', '1.5~2.5시간', '1시간', '5분'], f'시간 글자: {fm}')
        ov = await me.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')
        check(ov == 0, f'가로 넘침 없음 ({ov})')
        await b.close()
    print('\n'.join(errors) if errors else 'NO CONSOLE ERRORS')
    print(f'\n{len(fails)} FAIL' if fails else '\nALL PASS')
asyncio.run(main())
